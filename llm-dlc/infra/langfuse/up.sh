#!/usr/bin/env bash
# Start a local Langfuse (http://localhost:3000) for this repo's LLM traces.
# First run generates llm-dlc/infra/langfuse/.env with random secrets, a project, API keys
# and an admin login. Re-runs reuse it.
#
#   llm-dlc/infra/langfuse/up.sh          # start (or update) the stack
#   llm-dlc/infra/langfuse/up.sh down     # stop it; data stays in docker volumes
set -euo pipefail
cd "$(dirname "$0")"

if [[ ${1:-} == down ]]; then
  docker compose down
  exit
fi

if [[ ! -f .env ]]; then
  hex() { openssl rand -hex "$1"; }
  pg=$(hex 16) minio=$(hex 16)
  umask 077
  cat > .env <<EOF
# Generated by up.sh. Local secrets: never commit this file.
COMPOSE_PROJECT_NAME=langfuse
TELEMETRY_ENABLED=false
NEXTAUTH_URL=http://localhost:3000
NEXTAUTH_SECRET=$(hex 32)
SALT=$(hex 32)
ENCRYPTION_KEY=$(hex 32)
POSTGRES_PASSWORD=$pg
DATABASE_URL=postgresql://postgres:$pg@postgres:5432/postgres
CLICKHOUSE_PASSWORD=$(hex 16)
REDIS_AUTH=$(hex 16)
MINIO_ROOT_PASSWORD=$minio
LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY=$minio
LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY=$minio
LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY=$minio

# Headless init: org, project, API keys and an admin user.
LANGFUSE_INIT_ORG_ID=local
LANGFUSE_INIT_ORG_NAME=Local
LANGFUSE_INIT_PROJECT_ID=llm-traces
LANGFUSE_INIT_PROJECT_NAME="LLM traces"
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=pk-lf-$(hex 16)
LANGFUSE_INIT_PROJECT_SECRET_KEY=sk-lf-$(hex 16)
LANGFUSE_INIT_USER_EMAIL=admin@langfuse.local
LANGFUSE_INIT_USER_NAME=admin
LANGFUSE_INIT_USER_PASSWORD=$(hex 12)

# Read by llm-dlc/tools/sync.py
LANGFUSE_HOST=http://localhost:3000
EOF
  echo "Generated $(pwd)/.env"
fi

docker compose up -d
printf 'Waiting for Langfuse'
for _ in $(seq 120); do
  curl -fs http://localhost:3000/api/public/health >/dev/null 2>&1 && break
  printf .; sleep 2
done
echo
curl -fsS http://localhost:3000/api/public/health && echo
# shellcheck disable=SC1091
. ./.env
echo "Langfuse: http://localhost:3000  login: $LANGFUSE_INIT_USER_EMAIL / $LANGFUSE_INIT_USER_PASSWORD"
