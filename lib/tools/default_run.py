#!/usr/bin/env python3
"""The default test run's record, and the gate a push and a release ask.

The default run (`python3 lib/tools/test_costs.py run`, the unit and tool tiers) runs inline, in the working copy
(CLAUDE.md, Tests). When it passes, `test_costs.py run` writes the tree it tested to RECORD, outside the repository:
the git tree of `@` as jj snapshots it when the run starts, written only when the tree is the same when it ends, so
an edit made during the run leaves no record. A record covers a commit whose tree is the same, or differs from it
only in UNTESTED, files no test reads (traces, decisions, job results). The record is shared by the workspaces of
one machine: a run in one workspace covers the same tree in another.

    default_run.py last [--rev REV]          the latest passed run that covers REV (default @-)
    default_run.py gate [--rev REV] [--run]  exit 0 when one does (sync.py push and release.py cut ask this); with
                                             --run, a default run is started here when none does, and asked again

    default_run.py after-merge [--final] [--within SECONDS] [--memory SIZE] [--rust-jobs N]
                                             the default run after a merge, when it is due: it is the most expensive
                                             thing a session runs inline, and merges are frequent, so not every merge
                                             runs it (the user, 2026-11-18). It runs when the last one here failed,
                                             or when none has passed here within SECONDS (an hour); with --final,
                                             for the last merge of a run or before a push, whenever no passed run
                                             covers @-. It runs in a memory cap of its own (8G, `none` for no cap)
                                             with N Rust test binaries at a time (2), so that it cannot fill the
                                             memory of the session that started it (VF-037). Exits as the run does,
                                             0 when none was due.

One at a time: two runs in one workspace share cargo's target directory and the tests' work folders under it, and
overwrite what the other is reading (VF-034: two at once failed Rust tests that pass alone). `test_costs.py run`
holds `lock()` while it runs, and a second run waits for it.

Standard library only.
"""
from __future__ import annotations

import argparse
import fcntl
import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CACHE = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache") / "in-the-loop"
RECORD = CACHE / "default-runs.jsonl"
ATTEMPTS = CACHE / "default-run-attempts.json"  # each checkout's last whole default run: when, and whether it passed
WITHIN = 3600  # seconds a passed run here stands for the merges after it
KEPT = 200  # records kept, the newest
MARK = "default run:"
# Paths whose changes no test reads: a record still covers a commit that differs from its tree only here.
UNTESTED = ("llm-dlc/traces/", "llm-dlc/index.json", "llm-dlc/decisions/", "verification/results/",
            "verification/jobs/", "verification/findings.md", "llm-dlc/loop-summaries/", "llm-dlc/artifacts/")
# One file is untested in part: the table of sessions sync.py writes into llm-dlc/README.md, between these two
# lines. A promotion's publication record rewrites that table and nothing else in the file (sync.py promote), and
# no test reads it. The file's own text, outside the table, is covered like any other.
TABLE_FILE = "llm-dlc/README.md"
TABLE_BEGIN, TABLE_END = "<!-- index:begin (generated by llm-dlc/tools/sync.py) -->", "<!-- index:end -->"


def _out(cmd: list[str], cwd: Path) -> str | None:
    try:
        r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    except OSError:
        return None
    return r.stdout.strip() if r.returncode == 0 and r.stdout.strip() else None


def tree_of(rev: str, root: Path = ROOT) -> tuple[str, str] | None:
    """(the git tree of REV, its commit), or None outside a jj checkout. `@` is snapshotted first, as any jj command
    does, so its tree holds the working copy's files. Only at a workspace's own root: a tree exported inside one (a
    job's, under verification/.state) must not snapshot the workspace around it."""
    if not (root / ".jj").exists():
        return None
    commit =_out(["jj", "--quiet", "log", "--no-graph", "-r", rev, "-T", "commit_id"], root)
    tree = commit and _out(["git", "rev-parse", f"{commit}^{{tree}}"], root)
    return (tree, commit) if tree else None


def untested(path: str) -> bool:
    """Whether PATH is in UNTESTED: under one of its folders (`name/`), or one of its files exactly."""
    return any(path.startswith(u) if u.endswith("/") else path == u for u in UNTESTED)


def outside_table(text: str) -> str | None:
    """TEXT without the generated table between its two marks; None when it does not hold exactly one such table,
    so that a file whose marks were edited is compared whole."""
    start, end = text.find(TABLE_BEGIN), text.find(TABLE_END)
    if not 0 <= start < end or text.count(TABLE_BEGIN) != 1 or text.count(TABLE_END) != 1:
        return None
    return text[:start + len(TABLE_BEGIN)] + text[end:]


def table_only(run_tree: str, target_tree: str, root: Path = ROOT) -> bool:
    """Whether TABLE_FILE differs between the two trees in its generated table alone."""
    sides = []
    for tree in (run_tree, target_tree):
        try:
            r = subprocess.run(["git", "show", f"{tree}:{TABLE_FILE}"], cwd=root, capture_output=True, text=True)
        except OSError:
            return False
        rest = outside_table(r.stdout) if r.returncode == 0 else None
        if rest is None:
            return False
        sides.append(rest)
    return sides[0] == sides[1]


def covers(run_tree: str, target_tree: str, root: Path = ROOT) -> bool:
    """A run of RUN_TREE covers TARGET_TREE when they are the same, or differ only in UNTESTED and in the generated
    table of TABLE_FILE."""
    if run_tree == target_tree:
        return True
    names = _out(["git", "diff", "--name-only", "--no-renames", run_tree, target_tree], root)
    return names is not None and all(untested(p) or (p == TABLE_FILE and table_only(run_tree, target_tree, root))
                                     for p in names.splitlines())


def records(path: Path = RECORD) -> list[dict]:
    """The passed runs recorded, newest last."""
    try:
        lines = path.read_text().splitlines()
    except OSError:
        return []
    out = []
    for line in lines:
        try:
            out.append(json.loads(line))
        except ValueError:
            continue
    return out


def record(tree: str, commit: str, tally: str, root: Path = ROOT, path: Path = RECORD) -> None:
    entry = {"tree": tree, "commit": commit, "root": str(root), "when": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
             "tally": tally}
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        kept = records(path)[-(KEPT - 1):] + [entry]
        tmp = path.with_suffix(f".{os.getpid()}.tmp")
        tmp.write_text("".join(json.dumps(e) + "\n" for e in kept))
        tmp.replace(path)
    except OSError as e:
        print(f"{MARK} the record could not be written ({e})", flush=True)


def last(rev: str = "@-", root: Path = ROOT, path: Path = RECORD) -> dict | None:
    target = tree_of(rev, root)
    if target is None:
        return None
    for r in reversed(records(path)):
        if covers(r["tree"], target[0], root):
            return r
    return None


def attempted(root: Path = ROOT, ok: bool = True, path: Path | None = None, now: float | None = None) -> None:
    """Note that a whole default run ended in ROOT just now, and how."""
    path = path or ATTEMPTS
    try:
        try:
            all_ = json.loads(path.read_text())
        except (OSError, ValueError):
            all_ = {}
        all_[str(Path(root).resolve())] = {"when": now if now is not None else time.time(), "ok": ok}
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(f".{os.getpid()}.tmp")
        tmp.write_text(json.dumps(all_, indent=1) + "\n")
        tmp.replace(path)
    except OSError as e:
        print(f"{MARK} the run's end could not be noted ({e})", flush=True)


def due(root: Path = ROOT, final: bool = False, within: float = WITHIN, rev: str = "@-", path: Path | None = None,
        now: float | None = None) -> tuple[bool, str]:
    """(whether a default run is due after a merge in ROOT, why). See `after-merge` in the header."""
    now = now if now is not None else time.time()
    if last(rev, root):
        return False, f"a passed default run covers {rev} as it is"
    if final:
        return True, f"no passed default run covers {rev}, and this is the last merge"
    try:
        at = (json.loads((path or ATTEMPTS).read_text()) or {}).get(str(Path(root).resolve()))
    except (OSError, ValueError):
        at = None
    if not at:
        return True, "no default run is known to have ended here"
    ago = f"{max(0, int((now - at['when']) // 60))} min ago"
    if not at.get("ok"):
        return True, f"the last default run here failed ({ago}): it is taken up before new work"
    if now - at["when"] >= within:
        return True, f"the last default run here passed {ago}, more than {int(within // 60)} min"
    return False, (f"a default run passed here {ago}: the merges of the {int(within // 60)} min after it don't run another. "
                   f"The run's last merge does (--final), and so does a push")


def after_merge(root: Path = ROOT, final: bool = False, within: float = WITHIN, memory: str = "8G", rust_jobs: int = 2) -> int:
    run, why = due(root, final, within)
    if not run:
        print(f"{MARK} not run: {why}", flush=True)
        return 0
    argv = [sys.executable, str(root / "lib/tools/test_costs.py"), "run", "--rust-jobs", str(rust_jobs)]
    import shutil
    if memory != "none" and shutil.which("systemd-run"):
        argv = ["systemd-run", "--user", "--scope", "-q", "-p", f"MemoryMax={memory}", "-p", "MemorySwapMax=0", *argv]
    print(f"{MARK} running it: {why} ({'no memory cap' if argv[0] != 'systemd-run' else 'capped at ' + memory}, "
          f"{rust_jobs} Rust test binaries at a time)", flush=True)
    return subprocess.run(argv, cwd=root).returncode


class Started:
    """What `started()` saw: the tree a run began on, checked again when it ends."""

    def __init__(self, root: Path = ROOT):
        self.root = root
        self.at = tree_of("@", root)

    def passed(self, tally: str, path: Path = RECORD) -> None:
        if self.at is None:
            return
        now = tree_of("@", self.root)
        if now is None or now[0] != self.at[0]:
            print(f"{MARK} not recorded: the working copy changed during the run", flush=True)
            return
        record(self.at[0], self.at[1], tally, self.root, path)
        print(f"{MARK} recorded as passed for tree {self.at[0][:12]}", flush=True)


def lock(root: Path = ROOT):
    """An exclusive lock a run holds while it runs, in cargo's target directory; a second run waits for it. The lock
    is the open file: it goes when the run ends, however it ends."""
    target = Path(os.environ.get("CARGO_TARGET_DIR") or root / "lib" / "target")
    target.mkdir(parents=True, exist_ok=True)
    held = open(target / "test-run.lock", "w")
    try:
        fcntl.flock(held, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        print(f"{MARK} waiting: another test run holds {held.name}; one runs at a time", flush=True)
        fcntl.flock(held, fcntl.LOCK_EX)
    return held


def gate(rev: str = "@-", run: bool = False, root: Path = ROOT) -> tuple[bool, str]:
    """(whether a passed default run covers REV, what to say). With RUN, one is started when none does."""
    r = last(rev, root)
    if r is None and run:
        print(f"no passed default run covers {rev}: running it now (python3 lib/tools/test_costs.py run)",
              file=sys.stderr, flush=True)
        subprocess.run([sys.executable, str(root / "lib/tools/test_costs.py"), "run"], cwd=root)
        r = last(rev, root)
    if r:
        return True, f"the default run passed for {rev}: tree {r['tree'][:12]}, {r['when']} ({r['tally']})"
    return False, (f"no passed default run covers {rev}: run python3 lib/tools/test_costs.py run with nothing "
                   "uncommitted, and fix what fails")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="command", required=True)
    la = sub.add_parser("last")
    la.add_argument("--rev", default="@-")
    g = sub.add_parser("gate")
    g.add_argument("--rev", default="@-")
    g.add_argument("--run", action="store_true", help="start a default run here when none covers REV")
    m = sub.add_parser("after-merge")
    m.add_argument("--final", action="store_true", help="the last merge of a run, or before a push: whenever no passed run covers @-")
    m.add_argument("--within", type=float, default=WITHIN, metavar="SECONDS")
    m.add_argument("--memory", default="8G", help="the run's memory cap (`none` for no cap)")
    m.add_argument("--rust-jobs", type=int, default=2, metavar="N")
    a = ap.parse_args(argv)
    if a.command == "after-merge":
        return after_merge(ROOT, a.final, a.within, a.memory, a.rust_jobs)
    if a.command == "last":
        r = last(a.rev)
        print(json.dumps(r, indent=1) if r else f"no passed default run covers {a.rev}")
        return 0 if r else 1
    ok, said = gate(a.rev, a.run)
    print(said, file=sys.stdout if ok else sys.stderr)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
