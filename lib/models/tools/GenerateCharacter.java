/*
 * Writes java/lang/Character.java, the model of java.lang.Character, from the digit tables of the JDK this program
 * runs on: java tools/GenerateCharacter.java > java/lang/Character.java (run from lib/models/). The model has no
 * loops and no tables, so that JBMC needs no unwinding to read it: every run of code points with consecutive digit
 * values becomes one comparison, and the interpreter and JBMC compute the same function.
 */
import java.util.ArrayList;
import java.util.List;

public final class GenerateCharacter {
    public static void main(String[] args) {
        // Runs of code points whose radix-36 digit values go up by one per code point: the Nd digits in tens, the
        // Latin letters (ASCII and fullwidth) in twenty-sixes.
        List<int[]> runs = new ArrayList<>();
        int start = -1;
        for (int cp = 0; cp <= Character.MAX_CODE_POINT + 1; cp++) {
            int v = cp <= Character.MAX_CODE_POINT ? Character.digit(cp, 36) : -1;
            boolean continues = start >= 0 && v >= 0 && v == Character.digit(start, 36) + (cp - start);
            if (continues) {
                continue;
            }
            if (start >= 0) {
                runs.add(new int[] {start, cp - 1, Character.digit(start, 36)});
            }
            start = v >= 0 ? cp : -1;
        }
        // The model's isDigit is "digit value 0 to 9"; check that this is exactly the JDK's Nd test.
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
            int v = Character.digit(cp, 36);
            if (Character.isDigit(cp) != (v >= 0 && v <= 9)) {
                throw new IllegalStateException("isDigit and digit disagree at U+" + Integer.toHexString(cp));
            }
        }
        StringBuilder s = new StringBuilder();
        s.append("package java.lang;\n\n");
        s.append("/**\n");
        s.append(" * A model of {@code java.lang.Character} for jvmcontract's proofs: the digit tables of the JDK, written out as\n");
        s.append(" * comparisons. Generated by {@code tools/GenerateCharacter.java} from JDK ").append(System.getProperty("java.version"));
        s.append(" (the Unicode version is that JDK's); do not edit by hand.\n");
        s.append(" *\n");
        s.append(" * <p>The real class reads its tables through {@code CharacterData}, static arrays built from string literals in\n");
        s.append(" * static initializers, which JBMC does not read correctly (it answered that {@code digit('\\u0660', 16)} is not 0)\n");
        s.append(" * and the interpreter cannot run (their initialization needs {@code Class.getPrimitiveClass}). The model keeps the\n");
        s.append(" * functions that read the decimal-digit table, {@code digit} and {@code isDigit}, and {@code forDigit}; everything\n");
        s.append(" * else the real class does ({@code isLetter}, case mapping, surrogates, ...) is left to each engine, as before.\n");
        s.append(" *\n");
        s.append(" * <p>A run of code points with consecutive digit values is one comparison, ").append(runs.size()).append(" in all; there are no loops,\n");
        s.append(" * so JBMC needs no unwinding, and no tables, so no static initializer.\n");
        s.append(" */\n");
        s.append("public final class Character {\n\n");
        s.append("    /** The smallest radix {@link #digit} and {@link #forDigit} accept. */\n");
        s.append("    public static final int MIN_RADIX = 2;\n\n");
        s.append("    /** The largest radix {@link #digit} and {@link #forDigit} accept. */\n");
        s.append("    public static final int MAX_RADIX = 36;\n\n");
        s.append("    /** The smallest value of type {@code char}. */\n");
        s.append("    public static final char MIN_VALUE = '\\u0000';\n\n");
        s.append("    /** The largest value of type {@code char}. */\n");
        s.append("    public static final char MAX_VALUE = '\\uFFFF';\n\n");
        s.append("    /** The smallest Unicode code point. */\n");
        s.append("    public static final int MIN_CODE_POINT = 0x000000;\n\n");
        s.append("    /** The largest Unicode code point. */\n");
        s.append("    public static final int MAX_CODE_POINT = 0x10FFFF;\n\n");
        s.append("    private Character() {\n    }\n\n");
        s.append("    /**\n");
        s.append("     * Returns the numeric value of the character in the given radix: its decimal digit value for a decimal digit (Nd),\n");
        s.append("     * 10 to 35 for a Latin letter (ASCII or fullwidth, either case), and -1 when the character is neither, the value\n");
        s.append("     * is not less than the radix, or the radix is outside {@link #MIN_RADIX} to {@link #MAX_RADIX}.\n");
        s.append("     *\n");
        s.append("     * @param ch the character to be converted\n");
        s.append("     * @param radix the radix\n");
        s.append("     * @return the numeric value represented by the character in the given radix, or -1\n");
        s.append("     */\n");
        s.append("    public static int digit(char ch, int radix) {\n");
        s.append("        return digit((int) ch, radix);\n");
        s.append("    }\n\n");
        s.append("    /**\n");
        s.append("     * Returns the numeric value of the code point in the given radix; see {@link #digit(char, int)}.\n");
        s.append("     *\n");
        s.append("     * @param codePoint the code point to be converted\n");
        s.append("     * @param radix the radix\n");
        s.append("     * @return the numeric value represented by the code point in the given radix, or -1\n");
        s.append("     */\n");
        s.append("    public static int digit(int codePoint, int radix) {\n");
        s.append("        if (radix < MIN_RADIX || radix > MAX_RADIX) {\n");
        s.append("            return -1;\n");
        s.append("        }\n");
        s.append("        int value = value(codePoint);\n");
        s.append("        return value < radix ? value : -1;\n");
        s.append("    }\n\n");
        s.append("    /**\n");
        s.append("     * Tells whether the character is a decimal digit: of Unicode category Nd, which is exactly the characters whose\n");
        s.append("     * {@link #digit} value in radix 10 is not -1.\n");
        s.append("     *\n");
        s.append("     * @param ch the character to be tested\n");
        s.append("     * @return true if the character is a digit\n");
        s.append("     */\n");
        s.append("    public static boolean isDigit(char ch) {\n");
        s.append("        return isDigit((int) ch);\n");
        s.append("    }\n\n");
        s.append("    /**\n");
        s.append("     * Tells whether the code point is a decimal digit; see {@link #isDigit(char)}.\n");
        s.append("     *\n");
        s.append("     * @param codePoint the code point to be tested\n");
        s.append("     * @return true if the code point is a digit\n");
        s.append("     */\n");
        s.append("    public static boolean isDigit(int codePoint) {\n");
        s.append("        int value = value(codePoint);\n");
        s.append("        return value >= 0 && value <= 9;\n");
        s.append("    }\n\n");
        s.append("    /**\n");
        s.append("     * Determines the character representation for a digit in the given radix: {@code '0'} to {@code '9'}, then\n");
        s.append("     * {@code 'a'} to {@code 'z'}; the null character when the digit is not valid in the radix or the radix is outside\n");
        s.append("     * {@link #MIN_RADIX} to {@link #MAX_RADIX}.\n");
        s.append("     *\n");
        s.append("     * @param digit the number to convert to a character\n");
        s.append("     * @param radix the radix\n");
        s.append("     * @return the char representation of the digit in the radix, or the null character\n");
        s.append("     */\n");
        s.append("    public static char forDigit(int digit, int radix) {\n");
        s.append("        if (digit >= radix || digit < 0) {\n");
        s.append("            return '\\0';\n");
        s.append("        }\n");
        s.append("        if (radix < MIN_RADIX || radix > MAX_RADIX) {\n");
        s.append("            return '\\0';\n");
        s.append("        }\n");
        s.append("        if (digit < 10) {\n");
        s.append("            return (char) ('0' + digit);\n");
        s.append("        }\n");
        s.append("        return (char) ('a' - 10 + digit);\n");
        s.append("    }\n\n");
        s.append("    /** The digit value of a code point in radix 36, or -1: one comparison per run of consecutive values. */\n");
        s.append("    private static int value(int cp) {\n");
        for (int[] run : runs) {
            String lo = hex(run[0]), hi = hex(run[1]);
            if (run[0] == run[1]) {
                s.append("        if (cp == ").append(lo).append(") {\n            return ").append(run[2]).append(";\n        }\n");
            } else {
                s.append("        if (cp >= ").append(lo).append(" && cp <= ").append(hi).append(") {\n            return cp - ").append(lo);
                if (run[2] != 0) {
                    s.append(" + ").append(run[2]);
                }
                s.append(";\n        }\n");
            }
        }
        s.append("        return -1;\n");
        s.append("    }\n");
        s.append("}\n");
        System.out.print(s);
        System.err.println(runs.size() + " runs");
    }

    private static String hex(int cp) {
        return String.format("0x%04X", cp);
    }
}
