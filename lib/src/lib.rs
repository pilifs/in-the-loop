use std::fmt;

/// Which bounded model checker proves a harness: JBMC, the tool's own ([`bmc`]), or the tool's own where it
/// can and JBMC elsewhere.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Engine {
    Jbmc,
    Native,
    Auto,
}

impl std::str::FromStr for Engine {
    type Err = Error;

    fn from_str(s: &str) -> Result<Engine, Error> {
        match s {
            "jbmc" => Ok(Engine::Jbmc),
            "native" => Ok(Engine::Native),
            "auto" => Ok(Engine::Auto),
            other => Err(Error::new(format!("unknown engine {other:?}: jbmc, native or auto"))),
        }
    }
}

/// An error of the tool itself (I/O, a malformed input, a missing external tool), as opposed to a verdict.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Error(pub String);

impl Error {
    pub fn new(message: impl Into<String>) -> Error {
        Error(message.into())
    }
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Error {}

impl From<classfile::ParseError> for Error {
    fn from(e: classfile::ParseError) -> Error {
        Error(e.to_string())
    }
}

impl From<std::io::Error> for Error {
    fn from(e: std::io::Error) -> Error {
        Error(e.to_string())
    }
}

/// The three verdicts every verifier gives. "We could not check" is a failure, never a pass.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Verdict {
    /// The code behaves exactly as its contract, its previous version, or its invariants say.
    Verified,
    /// Behaviour changed, and the developer did not say so. A concrete witness is attached.
    Violation,
    /// The verifier refuses to give a verdict: not provably pure, not finite, the prover timed out, ...
    Unverifiable,
}

impl Verdict {
    pub fn label(self) -> &'static str {
        match self {
            Verdict::Verified => "✓ Verified",
            Verdict::Violation => "✗ Violation",
            Verdict::Unverifiable => "⚠ Unverifiable",
        }
    }

    pub fn exit_code(self) -> i32 {
        match self {
            Verdict::Verified => 0,
            Verdict::Violation | Verdict::Unverifiable => 1,
        }
    }
}

impl fmt::Display for Verdict {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Verdict::Verified => "verified",
            Verdict::Violation => "violation",
            Verdict::Unverifiable => "unverifiable",
        })
    }
}
