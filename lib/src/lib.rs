//! # jvmcontract
//!
//! Formal verification of JVM bytecode, as *contracts* derived from the compiled code and checked in next to it.
//! The build fails when the code no longer matches its contract; a developer who changes behaviour on purpose
//! regenerates the contract, and the pull request shows reviewers exactly which behaviour changed.
//!
//! Three kinds of contract, each with its own proof, plus a protocol model generated from the first:
//!
//! | Module | Contract | Proved by |
//! |---|---|---|
//! | [`verifier`] | **Behavioural**: the outcome of every input of a pure method with a finite domain | Purity from bytecode ([`purity`]), the domain from types ([`domain`]), then every input executed in the bytecode interpreter ([`interp`]) |
//! | [`equivalence`] | **Regression**: a method with unbounded inputs, arrays included, behaves as its previous version, outside the inputs the developer declares as changed | Both versions in one program ([`relocate`]), a generated bytecode harness ([`harness`]), bounded model checking with JBMC ([`jbmc`]), counterexamples shrunk and replayed in the interpreter ([`witness`]) |
//! | [`capabilities`] | **Capability**: every JDK capability (clock, network, reflection, ...) and library a module's bytecode can reach | A closed-world walk over every call site |
//! | [`tla`] | **Protocol**: a TLA+ operator generated from a behavioural contract, for a model checked by TLC | TLC, over every interleaving within bounds |
//!
//! Nothing here starts a JVM. Class files are parsed by [`classfile`], the JDK's own classes are read from its
//! image by [`jimage`] when their shape is needed, a few JDK classes are replaced by [`models`] that both engines
//! share, and the finite-domain executions run in [`interp`], an
//! interpreter for the subset of the JVM that pure domain code uses, with a dynamic effect monitor that makes the
//! purity proof complete over the executed domain.
//!
//! Every verdict can be written as SARIF ([`sarif`]) for GitHub code scanning and SonarQube.

