import java.sql.*;
import java.util.Map;
import org.springframework.jdbc.core.simple.SimpleJdbcInsert;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.dao.InvalidDataAccessApiUsageException;

public class PublicCaller {
    static final DriverManagerDataSource db = new DriverManagerDataSource("jdbc:h2:mem:keys;DB_CLOSE_DELAY=-1");
    static int rows() throws SQLException {
        try (var c=db.getConnection(); var s=c.createStatement(); var r=s.executeQuery("select count(*) from customers")) {
            r.next(); return r.getInt(1);
        }
    }
    static String insert(SimpleJdbcInsert action) throws SQLException {
        Number key=action.executeAndReturnKey(Map.of("name","Sven"));
        try (var c=db.getConnection(); var s=c.prepareStatement("select name from customers where id=?")) {
            s.setLong(1,key.longValue());
            try (var r=s.executeQuery()) {
                return "key-to-Sven=" + (r.next() && "Sven".equals(r.getString(1)) && !r.next()) + " rows=" + rows();
            }
        }
    }
    static String failure(Exception ex) {
        return ex.getClass().getSimpleName() + " column=" + (ex instanceof InvalidDataAccessApiUsageException
                && ex.getMessage().contains("ID") && ex.getMessage().toLowerCase().contains("generated key"));
    }
    public static String observe(String[] args) throws Exception {
        try (var c=db.getConnection(); var s=c.createStatement()) {
            s.execute("create table customers(id integer generated by default as identity primary key, name varchar(40))");
        }
        var action=new SimpleJdbcInsert(db).withTableName("customers").usingGeneratedKeyColumns("id");
        if (args[0].equals("valid")) return insert(action.usingColumns("name"));
        action.usingColumns("ID","name");
        String first="ok";
        if (args[0].equals("compile")) {
            try { action.compile(); } catch (RuntimeException e) { first=failure(e); }
            return first + " compiled=" + action.isCompiled() + " rows=" + rows();
        }
        try { insert(action); } catch (RuntimeException e) { first=failure(e); }
        first += " rows=" + rows();
        try { return first + " / " + insert(action.usingColumns("name")); }
        catch (RuntimeException e) { return first + " / " + e.getClass().getSimpleName() + " rows=" + rows(); }
    }
}
