#!/usr/bin/env python3
"""Find the examples relevant to a task, from examples/index.json.

  python3 examples/tools/find.py raft stale reply                 free text, ranked
  python3 examples/tools/find.py --tag liveness --approach D1     filters (each repeatable; all must match)
  python3 examples/tools/find.py --system Mica --verdict violation --limit 5
  python3 examples/tools/find.py --list-tags                      the vocabulary, with how many examples carry each tag
  python3 examples/tools/find.py --json idempotency retry         machine-readable, with summaries and notes

Words are matched against tags (worth most), the title, the symbol and system, the summary and the notes, after
lower-casing and a crude stemming, so "retries" finds "retry" and "replicas" finds "replica". Filters narrow the set
first. The index is regenerated by examples/tools/build.py (--index-only to rebuild it alone).
"""

import argparse
import json
import re
import sys
from pathlib import Path

EXAMPLES = Path(__file__).resolve().parents[1]
WEIGHTS = {"tags": 5, "title": 3, "symbol": 3, "system": 2, "summary": 1, "notes": 1}


def stem(word):
    word = word.lower()
    for suffix in ("ies", "es", "s", "ing", "ed"):
        if len(word) > len(suffix) + 3 and word.endswith(suffix):
            return word[: -len(suffix)] + ("y" if suffix == "ies" else "")
    return word


def words(text):
    return {stem(w) for w in re.findall(r"[a-z0-9]+", text.lower())}


def fields(e):
    tags = [t for facet in e["tags"].values() for t in facet]
    return {"tags": " ".join(tags + [t.replace("-", " ") for t in tags]), "title": e["title"],
            "symbol": e["symbol"].replace("#", " ").replace(".", " "), "system": e["system"],
            "summary": e["summary"], "notes": " ".join(e.get("notes", []))}


def score(e, query):
    if not query:
        return 0
    total = 0
    for name, text in fields(e).items():
        total += WEIGHTS[name] * len(query & words(text))
    return total


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("query", nargs="*", help="words to look for")
    p.add_argument("--tag", action="append", default=[], help="a tag from examples/tags.json; repeatable, all must match")
    p.add_argument("--approach", action="append", default=[], help="B8 B9 B10 B11 D1; repeatable, any may match")
    p.add_argument("--system", help="Box Office, Quorum, Crosscut, Mica, or a library's name (substring)")
    p.add_argument("--origin", choices=["constructed", "real-world"])
    p.add_argument("--verdict", choices=["violation", "verified", "unverifiable"])
    p.add_argument("--missed", action="store_true", help="only violations the existing tests missed")
    p.add_argument("--limit", type=int, default=10)
    p.add_argument("--json", action="store_true")
    p.add_argument("--list-tags", action="store_true")
    args = p.parse_args(argv)

    index = json.loads((EXAMPLES / "index.json").read_text())["examples"]
    vocabulary = json.loads((EXAMPLES / "tags.json").read_text())
    if args.list_tags:
        counts = {}
        for e in index:
            for facet in e["tags"].values():
                for t in facet:
                    counts[t] = counts.get(t, 0) + 1
        for facet, tags in vocabulary.items():
            if facet.startswith("$"):
                continue
            print(f"{facet}:")
            for tag, description in tags.items():
                print(f"  {tag:28} {counts.get(tag, 0):3}  {description}")
        return 0
    known = {t for f, tags in vocabulary.items() if not f.startswith("$") for t in tags}
    for t in args.tag:
        if t not in known:
            sys.exit(f"unknown tag {t!r}: --list-tags shows the vocabulary")

    def keep(e):
        tags = {t for facet in e["tags"].values() for t in facet}
        if not set(args.tag) <= tags:
            return False
        if args.approach and not set(args.approach) & set(e["approaches"]):
            return False
        if args.system and args.system.lower() not in e["system"].lower():
            return False
        if args.origin and e["origin"] != args.origin:
            return False
        if args.verdict and e["verdict"] != args.verdict:
            return False
        if args.missed and not (e["verdict"] == "violation" and e["existingTestsPassed"]):
            return False
        return True

    query = {stem(w) for w in args.query for w in re.findall(r"[a-z0-9]+", w.lower())}
    hits = [(score(e, query), e) for e in index if keep(e)]
    if query:
        hits = [h for h in hits if h[0] > 0]
    hits.sort(key=lambda h: (-h[0], h[1]["id"]))
    hits = hits[: args.limit]
    if args.json:
        print(json.dumps([{"score": s, **{k: e[k] for k in ("id", "path", "title", "origin", "system", "symbol", "approaches",
                                                           "verdictLabel", "tags", "summary", "notes")}} for s, e in hits],
                         indent=2, ensure_ascii=False))
        return 0
    if not hits:
        print("no example matches; try fewer words, or --list-tags")
        return 1
    for s, e in hits:
        tags = ", ".join(t for facet in e["tags"].values() for t in facet)
        print(f"{e['id']}  {e['title']}")
        print(f"     {e['path']}/README.md  [{', '.join(e['approaches'])}; {e['system']}; {e['verdictLabel']}]")
        print(f"     tags: {tags}")
        summary = e["summary"] if len(e["summary"]) < 300 else e["summary"][:297] + "..."
        print(f"     {summary}")
        print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
