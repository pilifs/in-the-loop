package net.terminalvalue.contracts;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * A behavioural contract: for one method, every input and its outcome. It is a text file checked in next to the
 * code, so a pull request that changes behaviour also changes this file, and a reviewer sees each changed case.
 *
 * @param cases input to outcome, in domain order
 */
record Contract(String target, String domain, Map<String, String> cases) {

    private static final String ARROW = " => ";

    static String fileName(String target) {
        String simple = target.substring(target.lastIndexOf('.') + 1);
        return simple.replace('#', '.') + ".contract";
    }

    static Contract read(Path file) throws IOException {
        String target = null;
        String domain = null;
        Map<String, String> cases = new LinkedHashMap<>();
        for (String line : Files.readAllLines(file)) {
            if (line.isBlank() || line.startsWith("#")) {
                continue;
            }
            if (line.startsWith("target: ")) {
                target = line.substring("target: ".length()).trim();
            } else if (line.startsWith("domain: ")) {
                domain = line.substring("domain: ".length()).trim();
            } else {
                int arrow = line.indexOf(ARROW);
                if (arrow < 0) {
                    throw new IOException(file + ": not a case: " + line);
                }
                cases.put(line.substring(0, arrow).trim(), line.substring(arrow + ARROW.length()).trim());
            }
        }
        if (target == null) {
            throw new IOException(file + " has no target line");
        }
        return new Contract(target, domain, cases);
    }

    void write(Path file) throws IOException {
        int width = cases.keySet().stream().mapToInt(String::length).max().orElse(0);
        List<String> lines = new ArrayList<>(List.of(
                "# Behavioural contract, generated by examples/tools/contracts. Do not edit: run `./gradlew updateContracts`.",
                "# It lists the outcome of every possible input, and the build checks it against the bytecode.",
                "# A change here is a change in what the code does: review it like an API change.",
                "target: " + target,
                "domain: " + domain,
                ""));
        cases.forEach((input, outcome) -> lines.add(input + " ".repeat(width - input.length()) + ARROW + outcome));
        Files.createDirectories(file.getParent());
        Files.write(file, lines);
    }
}
