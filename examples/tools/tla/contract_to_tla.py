#!/usr/bin/env python3
"""Turn a behavioural contract into a TLA+ operator.

The behavioural contract of OrderLifecycle#decide (examples/tools/contracts) lists the outcome of every input, and the
build proves that the bytecode behaves exactly that way. This script writes the same table as the TLA+ operator
Decide(status, input), so that the protocol model in examples/apps/boxoffice/spec runs the state machine the services
actually run. The link from bytecode to model is then generated, not transcribed.

Rows with a null status or input are left out: the protocol never passes null, and TLC cannot compare a string with a
record, which is how null would have to be encoded.

Usage: contract_to_tla.py OrderLifecycle.decide.contract OrderLifecycleContract.tla
"""

import re
import sys
from pathlib import Path

CASE = re.compile(r"^decide\((\w+|null), (.*?)\)\s*=> (.*)$")
INPUT = re.compile(r"^(\w+)\[(.*)\]$")
TRANSITION = re.compile(r"^Transition\[next=(\w+), effects=\[(.*?)\]\]$")


def main(contract_path, out_path):
    contract = Path(contract_path).read_text().splitlines()
    arms = []
    for line in contract:
        m = CASE.match(line)
        if not m:
            continue
        status, raw_input, outcome = m.groups()
        if status == "null" or raw_input == "null":
            continue
        arms.append((status, tla_input(raw_input), tla_outcome(outcome)))
    if not arms:
        sys.exit(f"{contract_path}: no cases found")
    lines = [
        "---- MODULE OrderLifecycleContract ----",
        f"\\* Generated by examples/tools/tla/contract_to_tla.py from {Path(contract_path).name}. Do not edit.",
        "\\* Each arm is one case of the behavioural contract of OrderLifecycle#decide, which examples/tools/contracts",
        "\\* proves against the compiled bytecode. Rows with a null status or input are omitted: the protocol never",
        "\\* passes null.",
        "",
        "Transition(next, effects) == [kind |-> \"Transition\", next |-> next, effects |-> effects]",
        "Unchanged == [kind |-> \"Unchanged\", effects |-> << >>]",
        "Rejected == [kind |-> \"Rejected\", effects |-> << >>]",
        "",
        "Decide(status, input) ==",
    ]
    for i, (status, inp, outcome) in enumerate(arms):
        prefix = "  CASE" if i == 0 else "    []"
        lines.append(f"{prefix} status = \"{status}\" /\\ input = {inp} -> {outcome}")
    lines += ["", "===="]
    Path(out_path).write_text("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(arms)} cases")


def tla_input(raw):
    m = INPUT.match(raw)
    if not m:
        sys.exit(f"cannot parse input {raw!r}")
    kind, fields = m.groups()
    parts = [f"kind |-> \"{kind}\""]
    for field in filter(None, fields.split(", ")):
        name, value = field.split("=", 1)
        parts.append(f"{name} |-> {tla_value(value)}")
    return "[" + ", ".join(parts) + "]"


def tla_value(value):
    if value in ("true", "false"):
        return value.upper()
    if re.match(r"^-?\d+$", value):
        return value
    return value if value.startswith('"') else f"\"{value}\""


def tla_outcome(outcome):
    m = TRANSITION.match(outcome)
    if m:
        next_status, effects = m.groups()
        seq = ", ".join(f"\"{e}\"" for e in filter(None, effects.split(", ")))
        return f"Transition(\"{next_status}\", <<{seq}>>)"
    if outcome.startswith("Unchanged["):
        return "Unchanged"
    if outcome.startswith("Rejected["):
        return "Rejected"
    if outcome.startswith("throws "):
        return f"[kind |-> \"Throws\", exception |-> \"{outcome[len('throws '):]}\", effects |-> << >>]"
    sys.exit(f"cannot translate outcome {outcome!r}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
